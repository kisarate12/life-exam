/** 学歴差分の数値から5段階を返す。境界: >=15, [5,15), [-4,5), [-15,-4), <-15 */
export function getEducationDiffTier(diff: number): EducationDiffTier {
  if (diff >= 15) return "over";
  if (diff >= 5) return "growth";
  if (diff >= -4) return "average";
  if (diff >= -15) return "underuse";
  return "impact";
}
